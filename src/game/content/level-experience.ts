export const maxLevel = levelThresholds.length;
export const maxExperience = levelThresholds[maxLevel - 1];

export function xpForLevel(level: number): number {
  if (!Number.isInteger(level) || level < 1) throw new RangeError("Level must be a positive integer.");
  return levelThresholds[Math.min(level, maxLevel) - 1];
}

export function levelForXp(xp: number): number {
  if (Number.isNaN(xp)) throw new RangeError("Experience must be a number.");
  const experience = Math.max(0, xp);
  let level = 1;
  while (level < maxLevel && experience >= levelThresholds[level]) level++;
  return level;
}

export function xpProgress(level: number, xp: number) {
  const start = xpForLevel(level);
  if (level >= maxLevel) return { xpInLevel: 0, xpToAdvance: 0 };
  const xpToAdvance = xpForLevel(level + 1) - start;
  return { xpInLevel: Math.min(xpToAdvance, Math.max(0, xp - start)), xpToAdvance };
}
